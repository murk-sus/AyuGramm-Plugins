#!/usr/bin/env python3
"""Rewrite the generated part of README.md (the fonts and the plugins by other authors) and the
README.md in every plugin and font folder.

Everything between `<!-- catalog:start -->` and `<!-- catalog:end -->` comes from index.json,
fonts/index.json and the meta.json / font.json files the team bot writes; the rest of the README
is edited by hand. Run after tools/build_index.py and tools/build_fonts_index.py.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START = "<!-- catalog:start -->"
END = "<!-- catalog:end -->"
KINDS = {"js": "JavaScript", "python": "Python", "lua": "Lua", "wasm": "Rust", "iosplug": "iOS"}


def cell(text):
    """One table cell: no line breaks, no column separators."""
    return re.sub(r"\s+", " ", str(text)).replace("|", "\\|").strip()


def author_link(author):
    """@nick becomes a link to the Telegram profile; anything else stays as written."""
    author = cell(author)
    match = re.fullmatch(r"@([A-Za-z0-9_]{4,32})", author)
    return f"[{author}](https://t.me/{match.group(1)})" if match else author


def folder_readme(title, author, details, description, screenshot, files, note):
    lines = [f"# {cell(title)}", "", "<!-- Generated by tools/build_readme.py: edit meta.json / font.json instead. -->", ""]
    lines.append(" · ".join([f"**Автор:** {author_link(author) if author else '—'}"] + details))
    lines += ["", cell(description) or "—", ""]
    if screenshot:
        lines += [f"![{cell(title)}]({screenshot})", ""]
    lines += ["**Файлы:** " + ", ".join(f"[{name}]({name})" for name in files), "", note, ""]
    return "\n".join(lines)


def write_folder_readmes():
    """README.md in every plugin and font folder: what it is, who made it, the screenshot."""
    fonts = json.loads((ROOT / "fonts/index.json").read_text(encoding="utf-8")).get("fonts", [])
    plugins = json.loads((ROOT / "index.json").read_text(encoding="utf-8")).get("plugins", [])
    shots = ("screenshot.png", "screenshot.jpg", "screenshot.webp")
    for font in fonts:
        folder = ROOT / "fonts" / font["id"]
        shot = next((name for name in shots if (folder / name).is_file()), None)
        files = sorted(p.name for p in folder.iterdir() if p.is_file() and p.name != "README.md")
        note = "Установка: каталог плагинов → раздел «Шрифты», или VoidGram → Оформление → Сообщения → Каталог шрифтов. Файл проверяется по SHA-256 `" + font["sha256"] + "`."
        text = folder_readme(font["name"], font.get("author", ""), ["шрифт"], font.get("description", ""), shot, files, note)
        (folder / "README.md").write_text(text, encoding="utf-8")
    for plugin in plugins:
        folder = ROOT / "plugins" / plugin["id"]
        shot = next((name for name in shots if (folder / name).is_file()), None)
        files = sorted(p.name for p in folder.iterdir() if p.is_file() and p.name != "README.md")
        details = [f"версия {cell(plugin['version'])}", KINDS.get(plugin.get("kind"), plugin.get("kind", ""))]
        if plugin.get("signature"):
            details.append("✓ официальный")
        if plugin.get("injects"):
            details.append("встраивается в приложение")
        note = "Установка: VoidGram → Плагины → значок сумки (каталог). Файл проверяется по SHA-256 `" + plugin["sha256"] + "`."
        text = folder_readme(plugin["name"], plugin["author"], details, plugin["description"], shot, files, note)
        (folder / "README.md").write_text(text, encoding="utf-8")


def section():
    fonts = json.loads((ROOT / "fonts/index.json").read_text(encoding="utf-8")).get("fonts", [])
    plugins = json.loads((ROOT / "index.json").read_text(encoding="utf-8")).get("plugins", [])
    community = [p for p in plugins if (ROOT / "plugins" / p["id"] / "meta.json").is_file()]
    lines = [START, "<!-- Generated by tools/build_readme.py from the catalog: edit meta.json / font.json instead. -->", ""]
    lines += ["## Fonts", "",
              "In the app: the **Fonts** section of the plugin catalog, or **Settings → VoidGram → Appearance → Messages → Font catalog**",
              "(27.0: **VoidGram → WhiteGram → Font catalog**).",
              "Every download is checked against the SHA-256 in [`fonts/index.json`](fonts/index.json).", ""]
    if fonts:
        lines += ["| Font | Author | What it is |", "|---|---|---|"]
        for font in sorted(fonts, key=lambda f: f["name"].lower()):
            path = font["url"].split("/main/", 1)[-1].rsplit("/", 1)[0]
            lines.append(f"| [{cell(font['name'])}]({path}) | {author_link(font.get('author', ''))} | {cell(font.get('description', ''))} |")
    else:
        lines.append("No fonts yet.")
    if community:
        lines += ["", "## Plugins by other authors", "",
                  "| Plugin | Author | Language | Version | What it does |", "|---|---|---|---|---|"]
        for plugin in sorted(community, key=lambda p: p["name"].lower()):
            path = plugin["url"].split("/main/", 1)[-1].rsplit("/", 1)[0]
            mark = " **official**" if plugin.get("signature") else ""
            lines.append(f"| [{cell(plugin['name'])}]({path}) | {author_link(plugin['author'])} | {KINDS.get(plugin.get('kind'), plugin.get('kind', ''))} "
                         f"| {cell(plugin['version'])} | {cell(plugin['description'])}{mark} |")
    lines += ["", END]
    return "\n".join(lines)


def main():
    path = ROOT / "README.md"
    text = path.read_text(encoding="utf-8")
    generated = section()
    if START in text and END in text:
        before, rest = text.split(START, 1)
        after = rest.split(END, 1)[1]
        text = before + generated + after
    elif "\n## Installing" in text:
        before, after = text.split("\n## Installing", 1)
        text = before.rstrip("\n") + "\n\n" + generated + "\n\n## Installing" + after
    else:
        text = text.rstrip("\n") + "\n\n" + generated + "\n"
    path.write_text(text, encoding="utf-8")
    write_folder_readmes()
    print("README.md: catalog section and folder READMEs updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
